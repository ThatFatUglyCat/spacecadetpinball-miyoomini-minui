inline uint16_t rgb565(uint8_t r, uint8_t g, uint8_t b) {
  return static_cast<uint16_t>(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3));
}

void draw_char(uint16_t* dst, int pitch_px, int x, int y, char ch, uint16_t fg) {
  unsigned idx = 0;
  const unsigned uc = static_cast<unsigned char>(ch);
  if (uc >= 32 && uc <= 127) idx = uc - 32;
  for (int row = 0; row < 7; ++row) {
    uint8_t bits = kFont[idx][row];
    for (int col = 0; col < 5; ++col) {
      if (bits & (1u << (4 - col))) {
        const int px = x + col;
        const int py = y + row;
        if (px >= 0 && px < kScreenW && py >= 0 && py < kScreenH)
          dst[py * pitch_px + px] = fg;
      }
    }
  }
}

void draw_text(uint16_t* dst, int pitch_px, int x, int y, const char* text, uint16_t fg) {
  int cx = x;
  int cy = y;
  for (const char* p = text; *p; ++p) {
    if (*p == '\n') {
      cx = x;
      cy += 10;
      continue;
    }
    draw_char(dst, pitch_px, cx, cy, *p, fg);
    cx += 6;
    if (cx > kScreenW - 6) {
      cx = x;
      cy += 10;
    }
  }
}

