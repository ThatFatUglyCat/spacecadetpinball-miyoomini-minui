void draw_char(uint16_t* dst, int pitch_px, int x, int y, char ch, uint16_t fg) {
  unsigned idx = 0;
  const unsigned uc = static_cast<unsigned char>(ch);
  if (uc >= 32 && uc <= 127) idx = uc - 32;
  for (int row = 0; row < 7; ++row) {
    uint8_t bits = kFont[idx][row];
    for (int col = 0; col < 5; ++col) {
      if (bits & (1u << (4 - col))) {
        const int px = x + col;
        const int py = y + row;
        if (px >= 0 && px < kScreenW && py >= 0 && py < kScreenH)
          dst[py * pitch_px + px] = fg;
      }
    }
  }
}

